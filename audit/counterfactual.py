"""Counterfactual fairness auditing for the Candidate Ranking System.

This module owns phase five of the pipeline. The :class:`CounterfactualAuditor`
builds a demographically swapped "twin" of each candidate -- swapping the
candidate name, gendered pronouns, and institution names -- and re-scores that
twin through the same scoring pipeline to detect scoring deltas that signal
demographic bias (Requirement 7).

This file provides the *pure* twin-construction surface plus the re-scoring
audit:

* :meth:`CounterfactualAuditor.swap_pronouns` -- whole-word, case-insensitive
  gendered pronoun swap (``he/him/his`` <-> ``she/her/hers``).
* :meth:`CounterfactualAuditor.swap_tokens` -- whole-word, case-insensitive
  replacement of names/institutions using a supplied mapping.
* :meth:`CounterfactualAuditor.build_twin` -- assembles the swapped resume text
  for a candidate using the configured name pairs, institution swaps, and the
  pronoun swap.
* :meth:`CounterfactualAuditor.audit` -- builds the twin, re-parses, re-enriches,
  and re-scores it through the injected collaborators (reusing the same scorer
  and vector store), computes the counterfactual delta and bias flag, updates the
  original result in place, and records the outcome in ``AUDIT_LOG``
  (Requirements 7.2-7.6, 7.9).

The three swap helpers are deterministic and perform no I/O, which keeps them
property-testable offline. Each swap is applied as a *single regex pass over an
alternation of all configured tokens* so that bidirectional swaps (for example
``he`` -> ``she`` and ``she`` -> ``he``) cannot cascade into one another. Any
token that has no configured counterpart is left unchanged (Requirement 7.1).

The swap tables (``COUNTERFACTUAL_NAME_PAIRS`` and ``INSTITUTION_SWAPS``) are
read exclusively from ``config`` so this module never redefines them
(Requirement 10.5).
"""

